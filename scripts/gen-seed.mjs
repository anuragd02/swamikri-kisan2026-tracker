// Generates src/data/seed.ts from docs/KISAN2026_TASKS.md.
// Run: npm run seed
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'docs/KISAN2026_TASKS.md'), 'utf8').replace(/\r\n/g, '\n');

const CREATED = '2026-11-14T00:00:00.000Z';
const OWNER = /^\*\*Owner:\*\* (.+?)\s*$/m.exec(src)?.[1];

// Category colours: distinct, and all >= 4.5:1 contrast on white so they also work as text.
const COLORS = { STALL: '#7C4A1E', DESIGN: '#1D5FA8', ASTRA: '#265022', TREAD: '#0F766E' };
const INBOX = { code: 'INBOX', name: 'Inbox (untriaged)', color: '#6B7280' };

const workstreams = [];
const tasks = [];
let ws = null;
let order = 0;

for (const line of src.split('\n')) {
  const h = /^## Category \d+: (.+?)\s*$/.exec(line);
  if (h) {
    ws = { name: h[1], code: null };
    order = 0;
    continue;
  }
  const row = /^\| ([a-z]+)-(\d{2}) \| (.+?) \| (\d{4}-\d{2}-\d{2}) \| (P[012]) \|$/.exec(line);
  if (!row) {
    if (/^\| [a-z]+-\d/.test(line)) throw new Error(`Unparsed task row: ${line}`);
    continue;
  }
  if (!ws) throw new Error(`Task before any category: ${line}`);
  const code = row[1].toUpperCase();
  if (!ws.code) {
    if (!COLORS[code]) throw new Error(`No colour for category ${code}`);
    ws.code = code;
    workstreams.push({ code, name: ws.name, color: COLORS[code], order: workstreams.length });
  } else if (ws.code !== code) {
    throw new Error(`Mixed id prefixes in category ${ws.name}: ${line}`);
  }
  tasks.push({
    id: `${row[1]}-${row[2]}`,
    title: row[3].trim(),
    workstream: code,
    parentId: null,
    order: order++,
    status: 'not_started',
    priority: row[5],
    ...(OWNER ? { owners: [OWNER] } : {}),
    dueDate: row[4],
    createdAt: CREATED,
    updatedAt: CREATED,
  });
}
workstreams.push({ ...INBOX, order: workstreams.length });

const total = /\*\*Total: (\d+) tasks\.\*\*/.exec(src);
if (total && Number(total[1]) !== tasks.length) throw new Error(`Expected ${total[1]} tasks, parsed ${tasks.length}`);

const out = `// GENERATED by scripts/gen-seed.mjs from docs/KISAN2026_TASKS.md. Do not edit by hand.
import type { GateDef, Settings, Task, Workstream } from '../types';

export const SEED_WORKSTREAMS: Workstream[] = ${JSON.stringify(workstreams, null, 2)};

/** Owner given to every seed task (also the first team member). */
export const SEED_OWNER = ${JSON.stringify(OWNER ?? '')};

/** Milestone gates. The current task list has none; tasks tagged G0..G7 with a milestone would show here. */
export const GATES: GateDef[] = [];

export const SEED_SETTINGS: Settings = {
  expoStart: '2026-12-09',
  expoEnd: '2026-12-13',
  setupDate: '2026-12-07',
  teamMembers: ${JSON.stringify(OWNER ? [OWNER] : [])},
};

export const PLAN_START = '2026-11-14';

export const SEED_TASKS: Task[] = ${JSON.stringify(tasks, null, 2)};
`;
writeFileSync(join(root, 'src/data/seed.ts'), out);
console.log(`Categories: ${workstreams.map((w) => `${w.code} (${tasks.filter((t) => t.workstream === w.code).length})`).join(', ')}; tasks: ${tasks.length}`);
